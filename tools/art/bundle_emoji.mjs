// Bundles Noto emoji PNGs for every emoji the game's code uses, so sprites look the same on every
// device instead of being traced from whatever emoji font the player's OS has (Segoe on Windows,
// Apple on macOS). Source images: the `emoji-datasource-google` npm package (Noto, Apache-2.0).
//
// Run from the repo root:
//   npm pack emoji-datasource-google@16.0.0 && tar xzf emoji-datasource-google-16.0.0.tgz
//   node tools/art/bundle_emoji.mjs ./package
// Re-run whenever a new emoji is added to src/js — an emoji missing from the manifest is silently
// traced from the OS emoji font instead, which is exactly the device-dependent look this avoids.
import fs from 'node:fs'
import path from 'node:path'

const [datasourceDir] = process.argv.slice(2)
if (!datasourceDir) {
  console.error('usage: node tools/art/bundle_emoji.mjs <emoji-datasource-google package dir>')
  process.exit(1)
}

const SRC_JS = 'src/js'
const OUT_DIR = 'src/img/emoji'
const MANIFEST = 'src/js/emoji-images.js'
const EMOJI_RE = /\p{Extended_Pictographic}(️|‍\p{Extended_Pictographic}️?|[\u{1F3FB}-\u{1F3FF}])*/gu
const stripVs = (s) => s.replace(/️/g, '')

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true })
  .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))

const used = new Set()
for (const file of walk(SRC_JS)) {
  if (!file.endsWith('.js') || path.resolve(file) === path.resolve(MANIFEST)) continue
  for (const m of fs.readFileSync(file, 'utf8').matchAll(EMOJI_RE)) used.add(stripVs(m[0]))
}

// emoji.json lists each emoji's codepoints and its image file name.
const table = JSON.parse(fs.readFileSync(path.join(datasourceDir, 'emoji.json'), 'utf8'))
const byEmoji = new Map()
for (const row of table) {
  if (!row.has_img_google) continue
  const emoji = String.fromCodePoint(...row.unified.split('-').map((h) => parseInt(h, 16)))
  byEmoji.set(stripVs(emoji), row.image)
}

fs.rmSync(OUT_DIR, { recursive: true, force: true })
fs.mkdirSync(OUT_DIR, { recursive: true })
const entries = []
const missing = []
for (const emoji of [...used].sort()) {
  const image = byEmoji.get(emoji)
  if (!image) { missing.push(emoji); continue }
  fs.copyFileSync(path.join(datasourceDir, 'img/google/64', image), path.join(OUT_DIR, image))
  entries.push(`  '${emoji}': '${image}',`)
}

fs.writeFileSync(MANIFEST, `// GENERATED by tools/art/bundle_emoji.mjs — do not edit by hand.
// Emoji (variation selectors stripped) → Noto PNG in src/img/emoji/ (Apache-2.0, see LICENSE-Noto.txt there).
export const EMOJI_IMAGES = {
${entries.join('\n')}
}
`)
console.log(`bundled ${entries.length} emoji into ${OUT_DIR}`)
if (missing.length) console.warn(`no Noto image for: ${missing.join(' ')}`)
